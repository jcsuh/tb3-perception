#!/usr/bin/env python3
"""
Kalibr AprilGrid PDF로 Gazebo 보드 모델을 만든다.

1) PDF를 고해상도 그림으로 바꾸고, 바깥 모서리 사각형까지 포함한 격자만 정확히 잘라낸다
   (아래쪽의 축 화살표와 설명 글자는 버린다)
2) 잘라낸 그림의 실제 크기가 설정(태그 크기, 간격)과 맞는지 검사한다
3) AprilTag 36h11로 검출해 태그 24개가 보이고 0번이 왼쪽 아래인지 검사한다 (좌우 반전 방지)
4) 모델 폴더를 쓴다: model.config, model.sdf, meshes/board.obj, materials/textures/board.png
   - 모델 원점 = Kalibr 보드 좌표계 원점 (0번 태그의 왼쪽 아래 모서리), x 오른쪽, y 위, z 앞(보는 쪽)

사용 예:
  python3 make_aprilgrid_model.py aprilgrid_a3.pdf <출력 폴더>/aprilgrid_a3 \
      --cols 6 --rows 4 --tag-size 0.05 --tag-spacing 0.3
"""
import argparse
import os
import subprocess
import sys
import tempfile

import cv2
import numpy as np

DPI = 300


def longest_run(mask):
    """1차원 bool 배열에서 가장 긴 True 구간 [시작, 끝)을 찾는다."""
    best, start = (0, 0), None
    for i, v in enumerate(list(mask) + [False]):
        if v and start is None:
            start = i
        elif not v and start is not None:
            if i - start > best[1] - best[0]:
                best = (start, i)
            start = None
    return best


def render_and_crop(pdf):
    """PDF를 DPI로 렌더링하고 격자 부분만 흑백으로 잘라낸다."""
    with tempfile.TemporaryDirectory() as tmp:
        base = os.path.join(tmp, 'page')
        subprocess.run(['pdftoppm', '-r', str(DPI), '-png', '-singlefile', pdf, base],
                       check=True)
        img = cv2.imread(base + '.png', cv2.IMREAD_GRAYSCALE)
    dark = img < 128
    r0, r1 = longest_run(dark.any(axis=1))           # 격자가 있는 행 (글자 줄 제외)
    c0, c1 = longest_run(dark[r0:r1].any(axis=0))    # 그 행들 안의 열
    crop = np.where(dark[r0:r1, c0:c1], 0, 255).astype(np.uint8)
    return crop


def detector_params():
    """
    AprilGrid용 검출 설정.

    Kalibr AprilGrid의 태그는 검은 테두리가 2칸이다 (OpenCV 기본값은 1칸).
    """
    if hasattr(cv2.aruco, 'ArucoDetector'):
        params = cv2.aruco.DetectorParameters()
    else:
        params = cv2.aruco.DetectorParameters_create()
    params.markerBorderBits = 2
    return params


def detect_tags(img):
    """태그(AprilTag 36h11)를 검출해 {id: 중심 픽셀}을 돌려준다 (OpenCV 4.6과 4.7+ 모두 지원)."""
    small = cv2.resize(img, None, fx=0.25, fy=0.25, interpolation=cv2.INTER_AREA)
    dictionary = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_APRILTAG_36h11)
    if hasattr(cv2.aruco, 'ArucoDetector'):
        detector = cv2.aruco.ArucoDetector(dictionary, detector_params())
        corners, ids, _ = detector.detectMarkers(small)
    else:
        params = detector_params()
        corners, ids, _ = cv2.aruco.detectMarkers(small, dictionary, parameters=params)
    if ids is None:
        return {}
    return {int(i): c[0].mean(axis=0) * 4 for c, i in zip(corners, ids.flatten())}


OBJ = """# AprilGrid board: origin = Kalibr target origin (tag 0 bottom-left corner)
# x right, y up, normal +z (front face)
v {x0:.6f} {y0:.6f} 0
v {x1:.6f} {y0:.6f} 0
v {x1:.6f} {y1:.6f} 0
v {x0:.6f} {y1:.6f} 0
vt 0 0
vt 1 0
vt 1 1
vt 0 1
vn 0 0 1
f 1/1/1 2/2/1 3/3/1
f 1/1/1 3/3/1 4/4/1
"""

SDF = """<?xml version="1.0"?>
<!--
  Kalibr AprilGrid {cols}x{rows}, tag {tag_mm:.0f} mm, spacing {spacing}
  printed board {w_mm:.0f} x {h_mm:.0f} mm (incl. outer corner squares)
  model origin = Kalibr target origin (tag 0 bottom-left corner), x right, y up, z = front
  generated by tb3p_gazebo/scripts/make_aprilgrid_model.py
-->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="board">
      <visual name="print">
        <geometry>
          <mesh><uri>model://{name}/meshes/board.obj</uri></mesh>
        </geometry>
        <material>
          <diffuse>1 1 1 1</diffuse>
          <ambient>1 1 1 1</ambient>
          <emissive>0.6 0.6 0.6 1</emissive>
          <pbr>
            <metal>
              <albedo_map>model://{name}/materials/textures/board.png</albedo_map>
              <emissive_map>model://{name}/materials/textures/board.png</emissive_map>
              <metalness>0.0</metalness>
              <roughness>1.0</roughness>
            </metal>
          </pbr>
        </material>
      </visual>
      <!-- foam board behind the print (5 mm) -->
      <visual name="backing">
        <pose>{cx:.6f} {cy:.6f} -0.0026 0 0 0</pose>
        <geometry><box><size>{w:.6f} {h:.6f} 0.005</size></box></geometry>
        <material><diffuse>0.9 0.9 0.9 1</diffuse><ambient>0.9 0.9 0.9 1</ambient></material>
      </visual>
      <collision name="collision">
        <pose>{cx:.6f} {cy:.6f} -0.0026 0 0 0</pose>
        <geometry><box><size>{w:.6f} {h:.6f} 0.005</size></box></geometry>
      </collision>
    </link>
  </model>
</sdf>
"""

CONFIG = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Kalibr AprilGrid calibration board ({w_mm:.0f} x {h_mm:.0f} mm)</description>
</model>
"""


def main():
    """명령줄에서 실행할 때의 시작점."""
    p = argparse.ArgumentParser(description='Kalibr AprilGrid PDF로 Gazebo 보드 모델을 만든다.')
    p.add_argument('pdf')
    p.add_argument('out_dir', help='모델 폴더 (이름이 곧 모델 이름)')
    p.add_argument('--cols', type=int, default=6)
    p.add_argument('--rows', type=int, default=4)
    p.add_argument('--tag-size', type=float, default=0.05)
    p.add_argument('--tag-spacing', type=float, default=0.3)
    a = p.parse_args()

    s = a.tag_size * a.tag_spacing                       # 모서리 사각형 한 변 (m)
    w = a.cols * a.tag_size + (a.cols + 1) * s           # 인쇄 보드 가로 (m)
    h = a.rows * a.tag_size + (a.rows + 1) * s           # 인쇄 보드 세로 (m)

    crop = render_and_crop(a.pdf)
    px_mm = 25.4 / DPI
    w_meas, h_meas = crop.shape[1] * px_mm / 1000, crop.shape[0] * px_mm / 1000
    print(f'board size  expected {w*1000:.1f} x {h*1000:.1f} mm, '
          f'image {w_meas*1000:.1f} x {h_meas*1000:.1f} mm')
    if abs(w_meas - w) > 0.001 or abs(h_meas - h) > 0.001:
        sys.exit('크기 불일치: PDF와 --cols/--rows/--tag-size/--tag-spacing 설정을 확인하세요')

    tags = detect_tags(crop)
    n = a.cols * a.rows
    print(f'tags detected {len(tags)} / {n}')
    if len(tags) != n:
        sys.exit('태그 검출 실패: 그림이 손상되었거나 뒤집혔을 수 있습니다')
    # 0번은 왼쪽 아래, 1번은 그 오른쪽 (그림 좌표: y는 아래로 증가)
    if not (tags[0][1] > tags[a.cols][1] and tags[1][0] > tags[0][0]):
        sys.exit('태그 배치가 예상(0번 왼쪽 아래, 오른쪽으로 증가)과 다릅니다')
    print('tag 0 bottom-left, ids increase to the right and up: OK')

    name = os.path.basename(os.path.normpath(a.out_dir))
    os.makedirs(os.path.join(a.out_dir, 'meshes'), exist_ok=True)
    os.makedirs(os.path.join(a.out_dir, 'materials', 'textures'), exist_ok=True)
    cv2.imwrite(os.path.join(a.out_dir, 'materials', 'textures', 'board.png'), crop)

    x0, y0, x1, y1 = -s, -s, w - s, h - s                 # 원점 = 0번 태그 왼쪽 아래 모서리
    with open(os.path.join(a.out_dir, 'meshes', 'board.obj'), 'w') as f:
        f.write(OBJ.format(x0=x0, y0=y0, x1=x1, y1=y1))
    fmt = {'name': name, 'cols': a.cols, 'rows': a.rows, 'tag_mm': a.tag_size * 1000,
           'spacing': a.tag_spacing, 'w': w, 'h': h, 'w_mm': w * 1000, 'h_mm': h * 1000,
           'cx': (x0 + x1) / 2, 'cy': (y0 + y1) / 2}
    with open(os.path.join(a.out_dir, 'model.sdf'), 'w') as f:
        f.write(SDF.format(**fmt))
    with open(os.path.join(a.out_dir, 'model.config'), 'w') as f:
        f.write(CONFIG.format(**fmt))
    print(f'wrote model {name} -> {a.out_dir}')


if __name__ == '__main__':
    main()
